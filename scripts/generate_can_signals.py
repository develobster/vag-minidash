def definitions(root=ROOT):
    # Compatibility catalogue: layouts come from the same authoritative VAG
    # matrix as vag_can_db. Legacy names/API remain stable for existing users.
    from generate_vag_can_db import load
    spec = load(root)
    aliases = {
        "rpm": ("engine.rpm", "engine", "rpm"),
        "speed_kph": ("vehicle.speed", "abs", "km/h"),
        "throttle_percent": ("driver.throttle", "engine", "%"),
        "coolant_c": ("engine.coolant_temperature", "engine", "degC"),
        "oil_c": ("engine.oil_temperature", "engine", "degC"),
    }
    rows = []
    for source in spec["definitions"]:
        if source["layout"] != "sourced" or source["signal"] not in aliases:
            continue
        signal, ecu, unit = aliases[source["signal"]]
        rows.append(dict(platform="MQB" if source["platform"] == "MQB" else "PQ35/PQ46",
            signal=signal, ecu=ecu, unit=unit, can_id=source["can_id"], dlc=source["dlc"],
            start_bit=source["start_bit"], bits=source["bits"], little=source["little"],
            signed=source["signed"], scale=source["scale"], offset=source["offset"],
            ttl_ms=source["ttl_ms"], source=source["source"], license=source["license"], quality="candidate"))
    return rows


