def definitions(root=ROOT):
    spec = json.loads((root / "data/can/platforms.json").read_text())
    if spec["schema_version"] != 1:
        raise ValueError("Unsupported schema")
    rows = []
    for platform, profile in spec["platforms"].items():
        entries = list(profile.get("signals", []))
        for source in profile.get("imports", []):
            catalogue = json.loads((root / source["path"]).read_text())
            by_id = {item["id"]: item for item in catalogue["definitions"]}
            for key in source["ids"]:
                item = by_id[key]
                layout = item["metadata"]["layout"]
                entries.append(dict(signal=item["canonical_name"], ecu=item["ecu"],
                    unit=item["unit"] or "", can_id=layout["can_id"], dlc=8,
                    start_bit=layout["start_bit"], bits=layout["length"],
                    little=layout["byte_order"] == "little", signed=layout["signed"],
                    scale=layout["factor"], offset=layout["offset"],
                    ttl_ms=int(item["ttl"] * 1000), source=item["provenance"]["source_url"],
                    license=item["provenance"]["license"]))
        seen = set()
        for item in entries:
            item = dict(item, platform=platform, quality="candidate")
            if item["signal"] in seen:
                raise ValueError("Duplicate platform signal")
            seen.add(item["signal"])
            for key in ("can_id", "dlc", "start_bit", "bits", "ttl_ms"):
                if type(item[key]) is not int:
                    raise ValueError("Integer layout required")
            if not 0 <= item["can_id"] <= 0x7ff or not 1 <= item["dlc"] <= 8 \
                    or not 1 <= item["bits"] <= 32 or item["start_bit"] < 0 \
                    or item["start_bit"] + item["bits"] > item["dlc"] * 8 \
                    or not 0 < item["ttl_ms"] <= 60000:
                raise ValueError("Invalid Classical CAN layout")
            if any(type(item[k]) is not bool for k in ("little", "signed")):
                raise ValueError("Boolean representation required")
            if not item["little"] and (item["bits"] % 8 or item["start_bit"] % 8):
                raise ValueError("Big-endian support is byte-aligned; Motorola bit numbering is unsupported")
            if any(isinstance(item[k], bool) or not isinstance(item[k], (float, int))
                   or not math.isfinite(item[k]) for k in ("scale", "offset")):
                raise ValueError("Finite numeric scaling required")
            if not item["source"].startswith("https://") or not item["license"]:
                raise ValueError("Source and license required")
            rows.append(item)
    return rows


