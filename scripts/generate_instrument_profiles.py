"""Generate/check the MCU numeric table from the same catalogue used by the host."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate():
    catalog = json.loads((ROOT / 'data/ui/instrument-profiles.json').read_text(encoding='utf8'))
    profiles = catalog['profiles']
    assert catalog['default'] == profiles[0]['id']
    assert profiles[0]['coolant_max'] > profiles[0]['coolant_min']
    assert len({p['id'] for p in profiles}) == len(profiles)
    lines = ['/* Generated by scripts/generate_instrument_profiles.py; do not edit. */',
             'static const md_instrument_profile_t profiles[] = {']
    for p in profiles:
        assert len(p['id']) < 48 and p['rpm_max'] > 0 and p['speed_max'] > 0
        lines.append('    {' + ','.join([json.dumps(p['id']), json.dumps(p['name'])] +
            [str(p[k]) for k in ('rpm_max','speed_max','coolant_min','coolant_max')]) + '},')
    return '\n'.join(lines + ['};', ''])

if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true')
    args=parser.parse_args();path=ROOT / 'firmware/main/ui_instrument_profiles.inc'
    expected=generate()
    if args.check:
        if path.read_text(encoding='utf8') != expected:
            raise SystemExit('Instrument table drift: run scripts/generate_instrument_profiles.py')
    else:
        path.write_text(expected,encoding='utf8')
