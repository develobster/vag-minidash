"""Generate matching firmware/host VAG matrices; no vehicle evidence promotion."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLATFORMS = {"PQ35_46": 0, "MQB": 1}
LAYOUTS = {"sourced": 0, "requested_experimental": 1}


def load(root=ROOT):
    data = json.loads((root / "data/can/vag_signals.json").read_text())
    if data["schema"] != 1 or len(set(data["signal_names"])) != len(data["signal_names"]):
        raise ValueError("Invalid schema/signal vocabulary")
    names = data["signal_names"]
    seen = set()
    for row in data["definitions"]:
        key = row["platform"], row["layout"], row["signal"]
        if key in seen or key[0] not in PLATFORMS or key[1] not in LAYOUTS or key[2] not in names:
            raise ValueError("Unknown/duplicate definition")
        seen.add(key)
        for field in ("can_id", "dlc", "start_bit", "bits", "ttl_ms"):
            if type(row[field]) is not int:
                raise ValueError("Integer CAN layout required")
        if not 0 <= row["can_id"] <= 0x7ff or not 1 <= row["dlc"] <= 8 or not 1 <= row["bits"] <= 32 \
                or not 1 <= row["ttl_ms"] <= 60000:
            raise ValueError("Invalid frame/field bounds")
        if type(row["little"]) is not bool or type(row["signed"]) is not bool:
            raise ValueError("Boolean representation required")
        positions = []
        bit = row["start_bit"]
        for _ in range(row["bits"]):
            positions.append(bit)
            bit = bit + 1 if row["little"] else bit + 15 if bit % 8 == 0 else bit - 1
        for field in ("sign_bit", "valid_bit"):
            if field in row:
                positions.append(row[field])
        for start, bits in ((row.get("mux_start", 0), row.get("mux_bits", 0)),
                            (row.get("term_start", 0), row.get("term_bits", 0))):
            positions.extend(range(start, start + bits))
        if any(type(bit) is not int or not 0 <= bit < row["dlc"]*8 for bit in positions):
            raise ValueError("Field outside payload")
        for field in ("scale", "offset", "minimum", "maximum", "term_scale"):
            value = row.get(field, 0)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                raise ValueError("Non-finite scaling/range")
        if row["minimum"] > row["maximum"] or row["quality"] != "candidate" or not row["license"]:
            raise ValueError("Invalid quality/range/license")
        if row["layout"] == "sourced" and not row["source"].startswith("https://github.com/"):
            raise ValueError("Pinned source required")
        if row.get("all_bits_mask", 0) >= 1 << row["bits"]:
            raise ValueError("Invalid bit predicate")
    return data


def outputs(data):
    names = data["signal_names"]
    c = "/* Generated by scripts/generate_vag_can_db.py; do not edit. */\n"
    c += "const char *const vag_signal_names[VAG_SIGNAL_COUNT]={" + ",".join(json.dumps(n) for n in names) + "};\n"
    c += "const vag_can_definition_t vag_can_definitions[]={\n"
    for row in data["definitions"]:
        fields = dict(can_id=row["can_id"], platform=PLATFORMS[row["platform"]], layout=LAYOUTS[row["layout"]],
                      signal=names.index(row["signal"]), dlc=row["dlc"], start_bit=row["start_bit"], bits=row["bits"],
                      little=int(row["little"]), signed_value=int(row["signed"]), sign_bit=row.get("sign_bit", -1),
                      valid_bit=row.get("valid_bit", -1), valid_value=row.get("valid_value", 0),
                      mux_start=row.get("mux_start", -1), mux_bits=row.get("mux_bits", 0), mux_value=row.get("mux_value", 0),
                      all_bits_mask=row.get("all_bits_mask", 0), scale=row["scale"], offset=row["offset"],
                      term_start=row.get("term_start", -1), term_bits=row.get("term_bits", 0), term_scale=row.get("term_scale", 0),
                      minimum=row["minimum"], maximum=row["maximum"], ttl_ms=row["ttl_ms"],
                      invalid_raw=row.get("invalid_raw", 0), has_invalid_raw=int("invalid_raw" in row), source=row["source"])
        c += "    {" + ",".join(f".{key}={json.dumps(value)}" for key, value in fields.items()) + "},\n"
    c += "};\nconst size_t vag_can_definition_count=sizeof(vag_can_definitions)/sizeof(vag_can_definitions[0]);\n"
    py = '"""Generated VAG layout data. All rows remain candidates."""\n'
    py += "SIGNAL_NAMES = " + repr(tuple(names)) + "\nDEFINITIONS = " + repr(tuple(data["definitions"])) + "\n"
    return {"firmware/main/vag_can_db_generated.inc": c, "minidash_live/vag_can_data.py": py}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs(load()).items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != content:
                parser.exit(1, "Regenerate VAG catalogue: " + path + "\n")
        else:
            target.write_text(content)


if __name__ == "__main__":
    main()
