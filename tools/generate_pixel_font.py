SCALES = {10:1,12:1,14:2,16:2,20:2,28:3,48:5}

def generate():
    chunks = ['/* Original MiniDash pixel font. Generated by tools/generate_pixel_font.py. MIT. */', '#include "lvgl.h"']
    for size,scale in SCALES.items():
        chunks.append(f'extern const lv_font_t md_ui_font_mono_{size};')
        bitmap=[]; descriptors=['{0}']
        for cp in range(32,127):
            char=chr(cp); rows=GLYPHS[char]; bits=[]
            if char!=' ':
                for row in rows:
                    for _ in range(scale):
                        for x in range(5): bits.extend([(row>>(4-x))&1]*scale)
            offset=len(bitmap)
            for start in range(0,len(bits),8):
                byte=0
                for i,bit in enumerate(bits[start:start+8]): byte|=bit<<(7-i)
                bitmap.append(byte)
            advance=6*scale if size!=12 else 7
            descriptors.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=0,.ofs_y=0}'%(offset,advance*16,5*scale if bits else 0,7*scale if bits else 0))
        chunks.append('static const uint8_t bitmap_%d[]={%s};'%(size,','.join(map(str,bitmap))))
        chunks.append('static const lv_font_fmt_txt_glyph_dsc_t glyphs_%d[]={%s};'%(size,',\n'.join(descriptors)))
        chunks.append('static const lv_font_fmt_txt_cmap_t cmap_%d[]={ {.range_start=32,.range_length=95,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY} };'%size)
        chunks.append('static const lv_font_fmt_txt_dsc_t dsc_%d={.glyph_bitmap=bitmap_%d,.glyph_dsc=glyphs_%d,.cmaps=cmap_%d,.cmap_num=1,.bpp=1};'%(size,size,size,size))
        chunks.append('const lv_font_t md_ui_font_pixel_%d={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=%d,.base_line=0,.dsc=&dsc_%d,.fallback=&md_ui_font_mono_%d};'%(size,size,size,size))
    return '\n'.join(chunks)+'\n'

